import { existsSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

/**
 * Regenerates `src/app/shared/ui/emoji-picker/emoji-data.ts` from `unicode-emoji-json` (a pinned
 * devDependency, used only here — the app has no runtime dependency on it) and the Twemoji SVGs
 * that `copy-emoji.mjs` placed in `public/assets/emoji/`.
 *
 * Run by hand after bumping `unicode-emoji-json` or `@twemoji/svg`:
 *   npm run generate-assets && node scripts/generate-emoji-data.mjs
 *
 * The output is committed. Every emoji written has a Twemoji asset (a newer Unicode emoji than the
 * bundled Twemoji draws is dropped, not left as a broken image), and an emoji is marked as taking
 * skin tones only when all five tone variants also have an asset.
 */
const require = createRequire(import.meta.url);
const groups = require('unicode-emoji-json/data-by-group.json');
const components = require('unicode-emoji-json/data-emoji-components.json');
const ASSETS = 'public/assets/emoji';
const OUT = 'src/app/shared/ui/emoji-picker/emoji-data.ts';

if (!existsSync(ASSETS)) {
    console.error(`${ASSETS} is missing; run "npm run generate-assets" first`);
    process.exit(1);
}

const TONES = [
    components.light_skin_tone,
    components.medium_light_skin_tone,
    components.medium_skin_tone,
    components.medium_dark_skin_tone,
    components.dark_skin_tone,
];

// Same rule @twemoji/api applies when it names an icon: FE0F is dropped unless the sequence is a ZWJ one.
function iconName(emoji) {
    const text = emoji.includes('‍') ? emoji : emoji.replace(/️/g, '');
    return [...text].map((c) => c.codePointAt(0).toString(16)).join('-');
}
const hasAsset = (emoji) => existsSync(`${ASSETS}/${iconName(emoji)}.svg`);

// Tones go after the first code point. That is only a valid sequence for a single person, so
// pairs (which carry one tone per person) are left untoned rather than producing a non-RGI emoji.
const PAIR_WORDS = /holding hands|couple|kiss|handshake|people hugging|family/;
function withTone(emoji, tone) {
    const [first, ...rest] = [...emoji.replace(/️/g, '')];
    return first + tone + rest.join('');
}

const labels = {
    'Smileys & Emotion': 'Smileys & emotion',
    'People & Body': 'People & body',
    'Animals & Nature': 'Animals & nature',
    'Food & Drink': 'Food & drink',
    'Travel & Places': 'Travel & places',
};

const categories = [];
const names = {};
const toneable = [];
let dropped = 0;

for (const group of groups) {
    const list = [];
    for (const entry of group.emojis) {
        if (!hasAsset(entry.emoji)) {
            dropped += 1;
            continue;
        }
        list.push(entry.emoji);
        names[entry.emoji] = entry.name;
        if (
            entry.skin_tone_support &&
            !PAIR_WORDS.test(entry.name) &&
            TONES.every((tone) => hasAsset(withTone(entry.emoji, tone)))
        ) {
            toneable.push(entry.emoji);
        }
    }
    categories.push({ label: labels[group.name] ?? group.name, emoji: list });
}

const body = `/**
 * GENERATED by scripts/generate-emoji-data.mjs from unicode-emoji-json — do not edit by hand.
 * Every emoji here has a bundled Twemoji SVG; ${dropped} newer ones the bundled set cannot draw were left out.
 */
export interface EmojiCategory {
    label: string;
    emoji: string[];
}

export const EMOJI_CATEGORIES: EmojiCategory[] = ${JSON.stringify(categories)};

/** CLDR short name per emoji, used by picker search. */
export const EMOJI_NAMES: Readonly<Record<string, string>> = ${JSON.stringify(names)};

/** Emoji that take a skin tone (single person, all five variants have an asset). */
export const EMOJI_TONEABLE: ReadonlySet<string> = new Set(${JSON.stringify(toneable)});
`;

writeFileSync(OUT, body);
console.log(
    `wrote ${OUT}: ${categories.reduce((n, c) => n + c.emoji.length, 0)} emoji, ${toneable.length} toneable, ${dropped} dropped`
);
